using A360.Administration.Domain.Entities;

namespace A360.Administration.Api.Contracts;

public sealed record CreateDeviceAssetPlotRequest(
    string? FloorPlanId,
    string? FloorPlanName,
    string? ItemType,
    string? ItemId,
    string? ItemCode,
    string? ItemName,
    string? AssetCategory,
    string? AssetType,
    string? Model,
    string? SerialNumber,
    string? LocationId,
    string? LocationPath,
    string? ZoneId,
    string? ZoneCode,
    string? ZoneName,
    double? PositionX,
    double? PositionY,
    double? Orientation,
    string? Icon,
    string? Color,
    string? Status,
    string? CreatedBy,
    string? TenantId,
    string? ClientId);

public sealed record DeviceAssetPlotResponse(
    string PlotId,
    string? FloorPlanId,
    string? FloorPlanName,
    string ItemType,
    string? ItemId,
    string? ItemCode,
    string ItemName,
    string? AssetCategory,
    string? AssetType,
    string? Model,
    string? SerialNumber,
    string? LocationId,
    string LocationPath,
    string? ZoneId,
    string? ZoneCode,
    string? ZoneName,
    double PositionX,
    double PositionY,
    double Orientation,
    string? Icon,
    string? Color,
    string? Status,
    DateTime? LastUpdated,
    string? LastUpdatedBy,
    string? CreatedBy,
    DateTime? CreatedAt,
    string? TenantId,
    string? ClientId)
{
    public static DeviceAssetPlotResponse FromEntity(DeviceAssetPlot plot)
    {
        return new DeviceAssetPlotResponse(
            plot.PlotId,
            plot.FloorPlanId,
            plot.FloorPlanName,
            plot.ItemType,
            plot.ItemId,
            plot.ItemCode,
            plot.ItemName,
            plot.AssetCategory,
            plot.AssetType,
            plot.Model,
            plot.SerialNumber,
            plot.LocationId,
            plot.LocationPath,
            plot.ZoneId,
            plot.ZoneCode,
            plot.ZoneName,
            plot.PositionX,
            plot.PositionY,
            plot.Orientation,
            plot.Icon,
            plot.Color,
            plot.Status,
            // "Last Updated" on the details panel: the last edit, or the creation time when never edited.
            plot.UpdatedAt ?? plot.CreatedAt,
            plot.UpdatedBy ?? plot.CreatedBy,
            plot.CreatedBy,
            plot.CreatedAt,
            plot.TenantId,
            plot.ClientId);
    }
}
